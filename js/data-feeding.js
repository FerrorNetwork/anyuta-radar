function doseColIdx(months) {
  return months < 6 ? 0 : months < 7 ? 1 : months < 8 ? 2 : months < 9 ? 3 : 4;
}
function doseValue(key, months) {
  const d = DOSES.find(x => x.key === key);
  return d ? d.v[doseColIdx(months)] : '–';
}
function doseTarget(key, months) {
  const v = doseValue(key, months);
  if (!v || v === '–' || v.includes('/') && !v.includes('–')) return null;
  const first = v.split('/')[0].trim();
  const nums = first.split('–').map(Number);
  return nums[nums.length - 1] || null;
}
function rampFor(target) {
  if (!target) return [];
  const steps = target <= 6 ? [1, 2, 3, 4, 5, 6] : [2.5, 5, 10, 20, 40, 80];
  const out = steps.filter(s => s < target);
  out.push(target);
  return out;
}
function fmtSpoon(g) {
  if (g === 2.5) return '½ ч. л., около 2–3 г';
  if (g === 5) return '1 ч. л., около 5 г';
  if (g === 10) return '2 ч. л., около 10 г';
  if (g === 20) return '4 ч. л., около 20 г';
  return g + ' г';
}

/* Дневник прикорма */
function foodStatus(st) {
  const map = {};
  st.foods.slice().sort((a, b) => (a.date < b.date ? -1 : 1)).forEach(f => {
    const m = map[f.food] || (map[f.food] = { first: f.date, last: f.date, count: 0, days: new Set(), worst: 'ok' });
    m.last = f.date;
    m.count++;
    m.days.add(f.date);
    if (f.reaction === 'strong' || (f.reaction === 'mild' && m.worst === 'ok')) m.worst = f.reaction;
  });
  return map;
}
function feedingNow(st) {
  const today = todayKey(), months = ageMonthsOn(st, today), weeks = ageWeeksOn(st, today), status = foodStatus(st);
  const inRamp = Object.entries(status).filter(([id, s]) => s.worst !== 'strong' && diffDays(today, s.first) < 7)
    .sort((a, b) => (a[1].first < b[1].first ? 1 : -1)).map(([id, s]) => ({ product: PRODUCTS.find(p => p.id === id), status: s })).filter(x => x.product);
  const current = inRamp[0] || null;
  const next = FOOD_ROUTE.map(id => PRODUCTS.find(p => p.id === id)).find(p => !status[p.id] && p.from <= months) || null;
  const firsts = Object.values(status).map(s => s.first).sort();
  const lastNew = firsts[firsts.length - 1] || null;
  const waitDays = lastNew ? Math.max(0, 3 - diffDays(today, lastNew)) : 0;
  const started = st.foods.length > 0;
  return { today, months, weeks, status, current, next, waitDays, started, tooEarly: weeks < 17 };
}

function exercisePlan(st, key) {
  const weeks = Math.max(0, ageWeeksOn(st, key));
  const fits = EXERCISES.filter(e => weeks >= e.from && weeks < e.to);
  const core = fits.filter(e => e.core), extra = fits.filter(e => !e.core);
  const slots = Math.max(0, 6 - core.length), dayNo = diffDays(key, '2020-01-01');
  const picked = [];
  for (let i = 0; i < Math.min(slots, extra.length); i++) picked.push(extra[(dayNo + i) % extra.length]);
  return [...core, ...picked].map(e => {
    const done = st.exlog[key + ':' + e.id] || 0;
    return { ...e, done, finished: done >= e.times, time: e.dur(weeks) };
  });
}
/* Сколько дней подряд выполнен хотя бы один подход */
function exerciseStreak(st, key) {
  let n = 0, day = key;
  if (!Object.keys(st.exlog).some(k => k.startsWith(day + ':'))) day = addDays(day, -1);
  while (Object.keys(st.exlog).some(k => k.startsWith(day + ':'))) { n++; day = addDays(day, -1); }
  return n;
}
